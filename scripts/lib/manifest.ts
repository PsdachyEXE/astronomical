/** Regenerates assets/MANIFEST.md from src/sfx.ts so the two never drift. */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { SFX, SFX_IDS, type SfxIndex } from "../../src/sfx";
import { ASSETS } from "./paths";

export const writeManifest = (index: SfxIndex): void => {
  const rows = SFX_IDS.map((id) => {
    const s = SFX[id];
    const d = index[id]?.duration ?? 0;
    const status = s.placeholder ? "**PLACEHOLDER**" : "final";
    return `| \`${s.file}\` | ${s.description} | ${d.toFixed(2)} s${s.loop ? ", loops" : ""} | ${status} | ${s.source} | ${s.licence} |`;
  });
  const text = `# Asset manifest

Generated by \`npm run make-sfx\` from \`src/sfx.ts\`. Edit that file, not this one.

Rule: effects are CC0 only, each listed with its source URL and licence. When a CC0 file could not be fetched, a stand-in was synthesised and is marked **PLACEHOLDER**. No slot is ever empty.

The build machine could not reach freesound.org, kenney.nl or opengameart.org (blocked by the environment's network policy), so all eleven Episode 1 effects are synthesised stand-ins. To replace one: download a CC0 file, convert it to 48 kHz 16-bit WAV at the same path, set \`placeholder: false\` with its source URL and licence in \`src/sfx.ts\`, and rerun \`npm run make-sfx\`.

## Effects

| File | Slot | Length | Status | Source | Licence |
| --- | --- | --- | --- | --- | --- |
${rows.join("\n")}

## Fonts

| File | Source | Licence |
| --- | --- | --- |
| \`fonts/IBMPlexMono-Regular.ttf\` | https://raw.githubusercontent.com/google/fonts/main/ofl/ibmplexmono/IBMPlexMono-Regular.ttf | SIL Open Font License 1.1 (\`fonts/OFL.txt\`) |
| \`fonts/IBMPlexMono-SemiBold.ttf\` | https://raw.githubusercontent.com/google/fonts/main/ofl/ibmplexmono/IBMPlexMono-SemiBold.ttf | SIL Open Font License 1.1 (\`fonts/OFL.txt\`) |

## Voice

| Files | Source | Licence |
| --- | --- | --- |
| \`voice/<episode>/*.wav\` | **PLACEHOLDER**: \`npm run tts\` in placeholder mode writes a silent clip per line (word count over the voice's pace) with a short tone at the start | Made for this project. A real provider's commercial licence must be confirmed before anything is published |
`;
  writeFileSync(join(ASSETS, "MANIFEST.md"), text);
};
